"""Export Microsoft Presidio's English pattern recognizers to presidio-data.js.

    pip install presidio-analyzer && python scripts/build_presidio.py

Copies each recognizer's regexes, base scores, context words and cleanup rules.
The validators (checksums etc.) are ported by hand in presidio.js; recognizers
listed in SKIP have validators that need large lookup tables and are left out.
"""
import json
import re
from importlib.metadata import version
from pathlib import Path

from presidio_analyzer import PatternRecognizer
from presidio_analyzer import predefined_recognizers as pr

SKIP = {
    "InVehicleRegistrationRecognizer", "SgUenRecognizer", "ZaTrafficRegisterNumberRecognizer",
    "ZaDriverLicenseRecognizer", "ZaLicensePlateRecognizer",
}
CONSTS = (
    "VALID_VERSIONS", "VALID_VARIANT_PREFIXES", "NIL_UUID", "ALLOWED_CITIZENSHIP_VALUES",
    "ALLOWED_LEGACY_RACE_VALUES", "ALLOWED_LEADING_DIGITS", "ALLOWED_PREFIXES", "VAT_PREFIX", "LEGACY_PREFIXES",
)

out = []
for name in sorted(dir(pr)):
    cls = getattr(pr, name)
    if not (isinstance(cls, type) and issubclass(cls, PatternRecognizer) and cls is not PatternRecognizer) or name in SKIP:
        continue
    r = cls()
    if r.supported_language != "en" or not r.patterns:
        continue
    ci = bool(r.global_regex_flags & re.IGNORECASE)
    pats = []
    for p in r.patterns:
        rx, pci = p.regex, ci
        if rx.startswith("(?i)"):
            rx, pci = rx[4:], True
        pats.append({"name": p.name, "re": rx, "score": p.score, "i": pci})
    o = {"cls": name, "entity": r.supported_entities[0], "patterns": pats, "context": r.context or []}
    if getattr(r, "replacement_pairs", None):
        o["replace"] = [list(x) for x in r.replacement_pairs]
    consts = {k: (sorted(getattr(r, k)) if isinstance(getattr(r, k), (set, frozenset)) else getattr(r, k)) for k in CONSTS if hasattr(r, k)}
    if consts:
        o["consts"] = consts
    out.append(o)

dest = Path(__file__).resolve().parent.parent / "presidio-data.js"
dest.write_text(
    f"// Generated by scripts/build_presidio.py from presidio-analyzer {version('presidio-analyzer')} (MIT License, Microsoft).\n"
    "// Do not edit by hand.\nexport default " + json.dumps(out, ensure_ascii=False) + "\n"
)
print(f"wrote {len(out)} recognizers to {dest}")
